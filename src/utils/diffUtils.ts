/**
 * The payoff of the whole app: compare the tree you started with against the
 * tree you dragged into shape, and emit something you can actually run.
 *
 * Nodes are paired by `id`, not by path — that is what makes a drag read as a
 * `git mv` (which preserves history) rather than a delete plus an add.
 */

import type { FileNode } from '../store/treeOps';

export interface RepoChange {
  id: string;
  type: 'move' | 'add' | 'delete';
  /** Current path, or the path it used to have for a delete. */
  path: string;
  oldPath?: string;
  nodeType: 'file' | 'folder';
  name: string;
  /** True when an ancestor carries the same change, making this one redundant. */
  isNestedUnderChangedParent?: boolean;
}

export interface RepoDiff {
  changes: RepoChange[];
  /** Changes with redundant descendants removed — what the script acts on. */
  topLevelChanges: RepoChange[];
  totalCount: number;
}

export const EMPTY_DIFF: RepoDiff = { changes: [], topLevelChanges: [], totalCount: 0 };

interface FlatNode {
  id: string;
  path: string;
  name: string;
  type: 'file' | 'folder';
}

function flatten(nodes: readonly FileNode[]): Map<string, FlatNode> {
  const map = new Map<string, FlatNode>();
  const walk = (list: readonly FileNode[]) => {
    for (const node of list) {
      map.set(node.id, { id: node.id, path: node.path, name: node.name, type: node.type });
      if (node.children) walk(node.children);
    }
  };
  walk(nodes);
  return map;
}

export function computeRepoDiff(
  baseline: readonly FileNode[] | null,
  current: readonly FileNode[],
): RepoDiff {
  if (!baseline) return EMPTY_DIFF;

  const before = flatten(baseline);
  const after = flatten(current);
  const changes: RepoChange[] = [];

  for (const [id, node] of after) {
    const original = before.get(id);
    if (!original) {
      changes.push({ id, type: 'add', path: node.path, nodeType: node.type, name: node.name });
    } else if (original.path !== node.path) {
      changes.push({
        id,
        type: 'move',
        path: node.path,
        oldPath: original.path,
        nodeType: node.type,
        name: node.name,
      });
    }
  }

  for (const [id, node] of before) {
    if (!after.has(id)) {
      changes.push({ id, type: 'delete', path: node.path, nodeType: node.type, name: node.name });
    }
  }

  const movedFolders = changes.filter((c) => c.type === 'move' && c.nodeType === 'folder');
  const deletedFolders = changes.filter((c) => c.type === 'delete' && c.nodeType === 'folder');
  const addedFolders = changes.filter((c) => c.type === 'add' && c.nodeType === 'folder');

  for (const change of changes) {
    if (change.type === 'move' && change.oldPath) {
      // A move is redundant only if a moved ancestor carries it on *both* sides.
      change.isNestedUnderChangedParent = movedFolders.some(
        (folder) =>
          folder.id !== change.id &&
          change.oldPath!.startsWith(folder.oldPath! + '/') &&
          change.path.startsWith(folder.path + '/'),
      );
    } else if (change.type === 'delete') {
      change.isNestedUnderChangedParent = deletedFolders.some(
        (folder) => folder.id !== change.id && change.path.startsWith(folder.path + '/'),
      );
    } else {
      change.isNestedUnderChangedParent = addedFolders.some(
        (folder) => folder.id !== change.id && change.path.startsWith(folder.path + '/'),
      );
    }
  }

  const topLevelChanges = changes.filter((c) => !c.isNestedUnderChangedParent);

  return { changes, topLevelChanges, totalCount: topLevelChanges.length };
}

